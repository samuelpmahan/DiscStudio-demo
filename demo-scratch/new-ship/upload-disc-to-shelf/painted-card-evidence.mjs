import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import JSZip from 'jszip';
import { createExperience, initialDraft } from './model.ts';
import { cloneCard } from './export-ui.ts';
import { renderCard } from './card-renderer.ts';
import { exportZip } from './export-queue.ts';
import { paintedDiscsEnabled } from './kompozition.ts';

if (!paintedDiscsEnabled) throw Error('Activate painted-discs with Crisp before running evidence.');
const app = createExperience(() => {});
const painting = await app.selectDraftDepiction(() => 0);
const hydrated = await app.hydrateSeed(initialDraft().mold);
const address = await app.save({ ...initialDraft(), mold: hydrated.address, nickname: 'Pressed fern', plastic: 'ESP', weight: 177 }, painting);
const card = cloneCard(app.bag()[0], 'vertical', 'u02');
assert.deepEqual(card.disc.renderer.flights, [5, 4, -1, 1]);
const png = await renderCard(card.disc, card.orientation, card.cardDesign);
const fallback = await renderCard({ ...card.disc, renderer: { ...card.disc.renderer, artSrc: undefined } }, card.orientation, card.cardDesign);
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
assert.notEqual(sha(png), sha(fallback));
const zip = await exportZip([card], { renderCard: item => renderCard(item.disc, item.orientation, item.cardDesign) });
const packageEntries = await JSZip.loadAsync(zip);
const manifest = JSON.parse(await packageEntries.file('manifest.json').async('string'));
const packaged = await packageEntries.file(manifest.cards[0].filename).async('nodebuffer');
assert.equal(sha(packaged), sha(png));
assert.equal(manifest.cards[0].sha256, sha(png));
const out = new URL('./evidence/', import.meta.url);
fs.writeFileSync(new URL('painted-card-actual.png', out), png);
fs.writeFileSync(new URL('painted-card-placeholder-control.png', out), fallback);
fs.writeFileSync(new URL('painted-card-actual.zip', out), zip);
fs.writeFileSync(new URL('painted-card-render.receipt.json', out), JSON.stringify({ kind: 'painted-card-render/v1', address, painterArtSha256: sha(app.bag()[0].art), pngSha256: sha(png), placeholderSha256: sha(fallback), zipSha256: sha(zip), manifestCard: manifest.cards[0], pngBytes: png.length, zipBytes: zip.length, packagedMatchesRendered: true }, null, 2) + '\n');
